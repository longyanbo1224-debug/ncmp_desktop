def judgements_for(voice: str, tier: str) -> tuple:
    """取某套语气的判断句池。voice 不认识就回落默认。"""
    if voice == "warm":
        return _WARM_JUDGEMENTS.get(tier, _WARM_JUDGEMENTS["mid"])
    if voice == "brief":
        return _BRIEF_JUDGEMENTS.get(tier, _BRIEF_JUDGEMENTS["mid"])
    return JUDGEMENTS.get(tier, JUDGEMENTS["mid"])


def closers_for(voice: str) -> tuple:
    """取某套语气的收尾句池（简短语气没有收尾）。"""
    if voice == "warm":
        return _WARM_CLOSERS
    if voice == "brief":
        return ()
    return CLOSERS


