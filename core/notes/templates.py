def tier_for_score(score) -> str:
    """分数 → 档位。无法解析时按中间档处理，不抛异常。"""
    try:
        value = int(str(score).strip())
    except (TypeError, ValueError):
        return "mid"
    if value >= 4:
        return "high"
    if value == 3:
        return "mid"
    return "low"


